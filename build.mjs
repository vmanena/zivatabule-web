import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {marked} from 'marked';
const markdown=await readFile('index.md','utf8');
const template=await readFile('template.html','utf8');
marked.setOptions({gfm:true,breaks:false});
const rendered=marked.parse(markdown);
const chunks=rendered.split(/(?=<h2>)/);
const hero='<section class="hero"><div class="hero-copy">'+chunks.shift()+'</div><div class="hero-art" aria-hidden="true"><div class="demo-top"><span class="demo-dot"></span><span class="demo-dot"></span><span class="demo-dot"></span><span class="demo-name">Živá tabule</span></div><div class="demo-grid"><span>◷<small>Časovač</small></span><span>▤<small>Hlasování</small></span><span>⌗<small>QR kódy</small></span><span>♧<small>Skupiny</small></span><span>✦<small>Losování</small></span><span>◉<small>Hodiny</small></span></div></div></section>';
const sections=chunks.map((chunk,i)=>'<section class="content-section section-'+i+'">'+chunk+'</section>');
const html=template.replace('{{CONTENT}}',hero+'<div class="audience-strip"><span>Základní školy</span><span>Střední školy</span><span>Kurzy a firemní vzdělávání</span></div><div class="content-sections">'+sections.join('')+'</div>');
await mkdir('dist',{recursive:true});
await writeFile('dist/index.html',html);
await copyFile('style.css','dist/style.css');
console.log('Built dist/index.html');
